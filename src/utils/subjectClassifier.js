/**
 * 한 문장/문항 텍스트의 과목별 점수 (v2.1: 퍼지 매칭 + critical 등급 추가)
 * @param {string} s - 검사할 텍스트
 * @param {number} [questionNumber] - 문항 번호 (optional, 도메인 검증용)
 * @returns {object} 각 과목별 점수
 */
export function scoreSubjects(s, questionNumber = null) {
  const sc = { economy: 0, politics: 0, history: 0, geography: 0, society: 0 };
  if (!s) return sc;

  for (const subj of SUBJECT_PRIORITY) {
    const kw = SUBJECT_KEYWORDS[subj];
    for (const k of kw.critical || []) if (fuzzyIncludes(s, k)) sc[subj] += 5;
    for (const k of kw.strong) if (fuzzyIncludes(s, k)) sc[subj] += 3;
    for (const k of kw.weak) if (fuzzyIncludes(s, k)) sc[subj] += 1;
  }

  // 문항 번호 기반 도메인 검증 (anti-hallucination)
  if (questionNumber !== null) {
    const hintDomain = getDomainByQuestionNumber(questionNumber);
    if (hintDomain) {
      sc[hintDomain] += 2; // 예상 도메인에 가중치 보너스
    }
  }

  return sc;
}

/**
 * 단일 텍스트 → 과목 ('unknown' 가능)
 * @param {string} s - 검사할 텍스트
 * @param {number} [questionNumber] - 문항 번호 (optional)
 * @returns {string} 과목명
 */
export function classifySubject(s, questionNumber = null) {
  const sc = scoreSubjects(s, questionNumber);
  let best = 'unknown', bestv = 1; // 최소 2점 이상 필요
  for (const subj of SUBJECT_PRIORITY) {
    if (sc[subj] > bestv) {
      bestv = sc[subj];
      best = subj;
    }
  }
  return best;
}

/**
 * 과목 레이블 반환
 */
export function getSubjectLabel(domain) {
  const labels = {
    geography: '지리',
    history: '역사',
    politics: '정치',
    economy: '경제',
    society: '사회',
  };
  return labels[domain] || domain;
}

/**
 * 大問 단위 carry-forward 보정: 같은 大問 안에서 unknown 문항은 본문 주제를 상속
 * items: [{ subject, newDaemun }] 를 받아 보정된 subject 배열을 반환
 * v2.1: 문항 번호 기반 도메인 사전 검증 추가
 */
export function carryForwardSubjects(items) {
  const out = items.map((x) => ({ ...x }));
  let last = 'unknown';

  // Forward pass
  for (let i = 0; i < out.length; i++) {
    if (out[i].newDaemun) last = 'unknown';
    if (out[i].subject !== 'unknown') {
      last = out[i].subject;
    } else if (last !== 'unknown') {
      out[i].subject = last;
      out[i].inherited = true;
    }
  }

  // Backward pass
  let next = 'unknown';
  for (let i = out.length - 1; i >= 0; i--) {
    if (out[i].subject !== 'unknown') {
      next = out[i].subject;
    } else if (next !== 'unknown' && !out[i].newDaemun) {
      out[i].subject = next;
      out[i].inherited = true;
    }
    if (out[i].newDaemun) {
      next = out[i].subject !== 'unknown' ? out[i].subject : 'unknown';
    }
  }

  return out;
}

