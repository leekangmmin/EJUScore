// ── Levenshtein 퍼지 매칭 임계값 ──
export const FUZZY_THRESHOLD = 0.72; // OCR 오타 허용: 72% 이상 일치

/**
 * 퍼지 매칭: 텍스트에 키워드가 포함되어 있는지 검사 (OCR 오타 허용)
 * @param {string} text - 검사할 텍스트
 * @param {string} keyword - 찾을 키워드
 * @param {number} threshold - 유사도 임계값 (0~1)
 * @returns {boolean}
 */
function fuzzyIncludes(text, keyword, threshold = FUZZY_THRESHOLD) {
  if (!text || !keyword) return false;
  const tLower = text.toLowerCase();
  const kLower = keyword.toLowerCase();
  
  // 정확 일치
  if (tLower.includes(kLower)) return true;
  
  // 키워드가 2글자 미만이면 정확 매칭만
  if (kLower.length < 2) return false;
  
  // 단어 단위 퍼지 매칭
  const words = tLower.split(/[\s,，.．、。()（）「」【】\n\r]+/).filter(w => w.length >= 2);
  for (const word of words) {
    const dist = levenshteinDistance(kLower, word);
    const maxLen = Math.max(kLower.length, word.length);
    if (maxLen > 0 && (1 - dist / maxLen) >= threshold) return true;
  }
  return false;
}

